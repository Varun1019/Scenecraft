"""Border Detection and Intelligent Full-Bleed Normalization for StoryForge.

Detects and cleanly eliminates unwanted borders, letterbox bars, pillarbox bars,
solid frames, and white/black margins generated by AI image providers (Google Flow / Nano Banana).
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Tuple, Optional
import numpy as np
from PIL import Image

logger = logging.getLogger(__name__)


@dataclass
class BorderInfo:
    has_border: bool
    top_px: int
    bottom_px: int
    left_px: int
    right_px: int
    crop_box: Tuple[int, int, int, int]  # (x1, y1, x2, y2)
    border_type: str
    original_size: Tuple[int, int]  # (w, h)
    clean_size: Tuple[int, int]     # (w, h)
    crop_area_ratio: float          # ratio of retained area to original
    safe_to_crop: bool
    flag_reason: Optional[str] = None


class BorderDetector:
    """Detects black bars, white margins, and uniform solid frames on image perimeters with robust gradient verification."""

    MAX_ROW_STD = 6.0
    BLACK_THRESH = 22.0
    WHITE_THRESH = 244.0
    MIN_BORDER_DEPTH = 3
    MAX_BORDER_DEPTH_RATIO = 0.22  # Bounded border search depth: borders don't exceed 22% of dimension unilaterally
    MAX_SAFE_CROP_RATIO = 0.65
    MIN_BOUNDARY_GRADIENT = 10.0  # Step gradient to distinguish actual borders from bright sky / natural gradients

    def _is_uniform_slice(self, line: np.ndarray) -> Tuple[bool, Optional[str]]:
        """Check if 1D pixel slice is uniform black, white, or flat grey."""
        mean_c = float(line.mean())
        std_c = float(line.std())
        if std_c < self.MAX_ROW_STD:
            if mean_c < self.BLACK_THRESH:
                return True, "black"
            if mean_c > self.WHITE_THRESH:
                return True, "white"
        return False, None

    def _has_boundary_step_gradient(self, arr: np.ndarray, border_idx: int, axis: int) -> bool:
        """Confirm that a candidate border terminates at a sharp contrast transition, avoiding false positives on bright scenes."""
        try:
            if axis == 0:
                row_prev = arr[border_idx - 1, :, :].mean()
                row_curr = arr[border_idx, :, :].mean()
                row_curr_std = arr[border_idx, :, :].std()
            else:
                row_prev = arr[:, border_idx - 1, :].mean()
                row_curr = arr[:, border_idx, :].mean()
                row_curr_std = arr[:, border_idx, :].std()

            contrast_diff = abs(float(row_curr) - float(row_prev))
            return (contrast_diff >= self.MIN_BOUNDARY_GRADIENT) or (float(row_curr_std) > self.MAX_ROW_STD * 1.8)
        except Exception:
            return True

    def scan_borders(self, image_path: Path) -> BorderInfo:
        """Scan image boundaries to detect unwanted borders."""
        img = Image.open(image_path).convert("RGB")
        w, h = img.size
        arr = np.array(img, dtype=np.float32)

        # Iteratively find left, right, top, bottom bounds
        # Use central 70% span when checking horizontal/vertical lines to avoid corner interference
        x_start = int(w * 0.15)
        x_end = int(w * 0.85)
        y_start = int(h * 0.15)
        y_end = int(h * 0.85)

        max_h_depth = int(h * self.MAX_BORDER_DEPTH_RATIO)
        max_w_depth = int(w * self.MAX_BORDER_DEPTH_RATIO)

        # 1. Top down
        top = 0
        top_type = None
        for r in range(max_h_depth):
            is_b, b_type = self._is_uniform_slice(arr[r, x_start:x_end, :])
            if is_b:
                top = r + 1
                top_type = b_type
            elif top > 0 and r < top + 2:
                # 1-2px edge bleed allowance
                if arr[r, x_start:x_end, :].std() < self.MAX_ROW_STD * 1.5:
                    top = r + 1
                else:
                    break
            else:
                break

        # Validate step gradient for top border
        if top >= self.MIN_BORDER_DEPTH and top < h - 1:
            if not self._has_boundary_step_gradient(arr, top, axis=0):
                # Smooth transition indicates bright sky/lighting, not an artificial border
                top = 0
                top_type = None

        # 2. Bottom up
        bottom = 0
        bottom_type = None
        for r in range(max_h_depth):
            is_b, b_type = self._is_uniform_slice(arr[h - 1 - r, x_start:x_end, :])
            if is_b:
                bottom = r + 1
                bottom_type = b_type
            elif bottom > 0 and r < bottom + 2:
                if arr[h - 1 - r, x_start:x_end, :].std() < self.MAX_ROW_STD * 1.5:
                    bottom = r + 1
                else:
                    break
            else:
                break

        if bottom >= self.MIN_BORDER_DEPTH and bottom < h - 1:
            if not self._has_boundary_step_gradient(arr, h - bottom, axis=0):
                bottom = 0
                bottom_type = None

        # 3. Left rightward
        left = 0
        left_type = None
        for c in range(max_w_depth):
            is_b, b_type = self._is_uniform_slice(arr[y_start:y_end, c, :])
            if is_b:
                left = c + 1
                left_type = b_type
            elif left > 0 and c < left + 2:
                if arr[y_start:y_end, c, :].std() < self.MAX_ROW_STD * 1.5:
                    left = c + 1
                else:
                    break
            else:
                break

        if left >= self.MIN_BORDER_DEPTH and left < w - 1:
            if not self._has_boundary_step_gradient(arr, left, axis=1):
                left = 0
                left_type = None

        # 4. Right leftward
        right = 0
        right_type = None
        for c in range(max_w_depth):
            is_b, b_type = self._is_uniform_slice(arr[y_start:y_end, w - 1 - c, :])
            if is_b:
                right = c + 1
                right_type = b_type
            elif right > 0 and c < right + 2:
                if arr[y_start:y_end, w - 1 - c, :].std() < self.MAX_ROW_STD * 1.5:
                    right = c + 1
                else:
                    break
            else:
                break

        if right >= self.MIN_BORDER_DEPTH and right < w - 1:
            if not self._has_boundary_step_gradient(arr, w - right, axis=1):
                right = 0
                right_type = None

        # Filter negligible noise
        if top < self.MIN_BORDER_DEPTH and bottom < self.MIN_BORDER_DEPTH:
            top = 0
            bottom = 0
        if left < self.MIN_BORDER_DEPTH and right < self.MIN_BORDER_DEPTH:
            left = 0
            right = 0

        has_border = (top > 0 or bottom > 0 or left > 0 or right > 0)
        x1 = left
        y1 = top
        x2 = w - right
        y2 = h - bottom

        clean_w = max(0, x2 - x1)
        clean_h = max(0, y2 - y1)
        area_ratio = (clean_w * clean_h) / float(w * h) if (w * h) > 0 else 0.0

        types = set(filter(None, [top_type, bottom_type, left_type, right_type]))
        if "black" in types and "white" in types:
            border_name = "mixed_border"
        elif "black" in types:
            border_name = "black_letterbox" if (top > 0 or bottom > 0) else "black_pillarbox"
        elif "white" in types:
            border_name = "white_margin"
        else:
            border_name = "clean_edge_to_edge" if not has_border else "uniform_frame"

        safe = True
        flag = None
        if has_border:
            if area_ratio < self.MAX_SAFE_CROP_RATIO:
                safe = False
                flag = f"Border too thick ({100 - area_ratio*100:.1f}% of image). Auto-crop aborted to avoid cutting scene content."
            elif clean_w < 100 or clean_h < 100:
                safe = False
                flag = f"Cropped dimension too small: {clean_w}x{clean_h}."

        return BorderInfo(
            has_border=has_border,
            top_px=top,
            bottom_px=bottom,
            left_px=left,
            right_px=right,
            crop_box=(x1, y1, x2, y2),
            border_type=border_name,
            original_size=(w, h),
            clean_size=(clean_w, clean_h),
            crop_area_ratio=area_ratio,
            safe_to_crop=safe,
            flag_reason=flag,
        )

    def clean_image(
        self,
        image_path: Path,
        output_path: Optional[Path] = None,
        target_aspect_ratio: str = "16:9",
    ) -> Tuple[Path, BorderInfo]:
        """Detect and crop unwanted borders, returning clean full-bleed image."""
        p = Path(image_path)
        out = Path(output_path) if output_path else p
        out.parent.mkdir(parents=True, exist_ok=True)

        info = self.scan_borders(p)
        if not info.has_border:
            if p != out:
                import shutil
                shutil.copy2(p, out)
            return out, info

        if not info.safe_to_crop:
            logger.warning(f"Border detected on {p.name} but flagged: {info.flag_reason}")
            if p != out:
                import shutil
                shutil.copy2(p, out)
            return out, info

        img = Image.open(p).convert("RGB")
        cropped = img.crop(info.crop_box)
        cw, ch = cropped.size

        target_ratio = 16.0 / 9.0 if target_aspect_ratio == "16:9" else 9.0 / 16.0
        current_ratio = cw / float(ch)

        if abs(current_ratio - target_ratio) > 0.05:
            if current_ratio > target_ratio:
                new_w = int(ch * target_ratio)
                off_x = (cw - new_w) // 2
                cropped = cropped.crop((off_x, 0, off_x + new_w, ch))
            else:
                new_h = int(cw / target_ratio)
                off_y = (ch - new_h) // 2
                cropped = cropped.crop((0, off_y, cw, off_y + new_h))

        # Standardize resolution back to original dimensions for consistent video pipeline sizing
        if cropped.size != info.original_size:
            cropped = cropped.resize(info.original_size, Image.Resampling.LANCZOS)

        cropped.save(out, quality=95)
        logger.info(f"Cleaned unwanted {info.border_type} ({info.crop_box}) -> {out.name}")
        return out, info
